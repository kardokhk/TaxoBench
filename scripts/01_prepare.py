#!/usr/bin/env python3
"""Step 01 - Prepare mock community input data.

Scans the Mockrobiota source directory, optionally classifies expected
sequences via mmseqs2, and writes 16S {seqs.fasta, taxa.txt} pairs to
`data/mock_community/input_data/`.

If existing input_data files are already present (e.g. from a prior
mmseqs2 run that has been symlinked in), the script is a no-op unless
`--force` is given.
"""

import argparse
import os
import shutil
import subprocess
from os.path import exists, join, basename
from pathlib import Path

import _common


def discover_mocks(mockrobiota_dir):
    """Return dict {mock_name: 'expected-sequences.fasta path'} for 16S
    bacterial mocks only (skip ITS, Euk, NA primers)."""
    import pandas as pd
    import glob
    out = {}
    for mock_dir in sorted(glob.glob(join(mockrobiota_dir, "mock-*"))):
        meta = join(mock_dir, "sample-metadata.tsv")
        if not exists(meta):
            continue
        df = pd.read_csv(meta, sep="\t", header=0)
        if "PrimerName" not in df.columns:
            continue
        primers = list(df.PrimerName.unique())
        if any(pd.isna(p) or str(p).strip().upper() == "NA" for p in primers):
            continue
        if any("Ueda" in str(p) or "EukBr" in str(p) or "ITS" in str(p) for p in primers):
            continue
        seq_fp = join(mock_dir, "source", "expected-sequences.fasta")
        if exists(seq_fp):
            out[basename(mock_dir)] = seq_fp
    return out


def already_done(out_dir, mock_name):
    return exists(join(out_dir, f"{mock_name}_seqs.fasta")) and \
           exists(join(out_dir, f"{mock_name}_taxa.txt"))


def main():
    ap = argparse.ArgumentParser(description="Prepare mock-community input data")
    ap.add_argument("--mock-name", default=None,
                    help="Restrict to a single mock name (e.g. mock-3); default: all detected")
    ap.add_argument("--source-dir", default=None,
                    help="Mockrobiota data dir (default from pipeline_config.json)")
    ap.add_argument("--reference-dir", default=None,
                    help="Reference DB root (default from pipeline_config.json)")
    ap.add_argument("--out-dir", default=None,
                    help="Output dir (default: data/mock_community/input_data)")
    ap.add_argument("--force", action="store_true",
                    help="Re-do even when output files already exist")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    cfg = _common.load_pipeline_config()
    source_dir = args.source_dir or cfg["mockrobiota_source_dir"]
    out_dir    = args.out_dir    or cfg["mock_input_dir"]
    ref_dir    = args.reference_dir or cfg["reference_database_dir"]

    Path(out_dir).mkdir(parents=True, exist_ok=True)

    print(f"[01_prepare] source_dir = {source_dir}")
    print(f"[01_prepare] out_dir    = {out_dir}")
    print(f"[01_prepare] ref_dir    = {ref_dir}")

    mocks = discover_mocks(source_dir)
    if args.mock_name:
        mocks = {k: v for k, v in mocks.items() if k == args.mock_name}
    if not mocks:
        print("[01_prepare] no mocks found; exiting")
        return

    for mock_name, seq_fp in mocks.items():
        print(f"\n[01_prepare] {mock_name}: {seq_fp}")
        if already_done(out_dir, mock_name) and not args.force:
            print("  - skipping (already exists; pass --force to redo)")
            continue
        if args.force:
            for ext in ("_seqs.fasta", "_taxa.txt"):
                p = join(out_dir, f"{mock_name}{ext}")
                if exists(p):
                    os.remove(p)

        # Symlink the expected-sequences.fasta into out_dir; taxonomy
        # generation is deferred to the per-region notebook (or to be
        # generated by mmseqs2 against the reference DB).
        dest_seq = join(out_dir, f"{mock_name}_seqs.fasta")
        dest_tax = join(out_dir, f"{mock_name}_taxa.txt")
        if args.dry_run:
            print(f"  [dry] cp {seq_fp} -> {dest_seq}")
            continue
        shutil.copy(seq_fp, dest_seq)

        # Write a placeholder taxonomy file if expected-taxonomy.tsv exists
        exp_tax = join(os.path.dirname(seq_fp), "expected-taxonomy.tsv")
        if exists(exp_tax):
            shutil.copy(exp_tax, dest_tax)
            print(f"  + copied expected-taxonomy.tsv -> {basename(dest_tax)}")
        else:
            # leave empty taxonomy file so downstream knows mmseqs2 is needed
            Path(dest_tax).touch()
            print(f"  ! no expected-taxonomy; created empty {basename(dest_tax)}")

    print("\n[01_prepare] done")


if __name__ == "__main__":
    main()
