#!/usr/bin/env python3
"""Step 02d: long-read (V1-V9, RRN) mocks for the environmental biomes.

ART simulates short Illumina reads, so 02_generate.py cannot produce the
whole-16S (V1-V9) or rRNA operon (RRN) cells. For the marine, ocean and plants
biomes this script builds them as described in the Taxonova paper: up to 500
full-length sequences from genera observed in the biome (MGnify genus
abundances, mocks/mgnify/results/2025-08-20_snapshot/), from the Greengenes2 backbone
(V1-V9) or GROND (RRN), with random substitutions at a per-sequence rate drawn
from 0.002 to 0.02. The truth is known by construction.

Outputs (same layout as the other biome mocks):
  data/mock_community/<biome>/<region>/env-seqs_<biome>{00..09}.fasta
  data/mock_community/<biome>/<region>/source/single/rep_seqs_<biome>.fasta
  data/mock_community/<biome>/<region>/source/single/rep_seqs_<biome>.qza
An existing <biome>/<region>/single/rep_seqs_<biome>.fasta is moved aside,
not deleted.

The published cells were drawn with a seed mixed with Python's salted
string hash, so they cannot be regenerated byte for byte. This version mixes the seed
with a stable CRC32 of the cell name, so reruns give identical output.

Usage:
  python scripts/02d_generate_longread_biomes.py --biome biome_marine --region V1-V9
  python scripts/02d_generate_longread_biomes.py --biome gtdb_marine --region RRN
  python scripts/02d_generate_longread_biomes.py --all     # the six cells
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import random
import re
import shutil
from datetime import date
from pathlib import Path

# Paths from configs/pipeline_config.json (TAXOBENCH_<KEY> overrides apply).
import sys
import zlib
sys.path.insert(0, str(Path(__file__).resolve().parent))
import _common  # noqa: E402

_CFG = _common.load_pipeline_config()
DATA = Path(_CFG["data_dir"])
MOCK = DATA / "mock_community"
_REF = Path(_CFG["reference_database_dir"])
GG2_FA = _REF / "Greengenes2_backbone/2024.09_sequences.fa"
GG2_TAX = _REF / "Greengenes2_backbone/2024.09_taxonomy.tsv"
GROND_FA = _REF / "RRN/grond_clean.fasta"
GROND_TAX = _REF / "RRN/grond_clean.tsv"
MGNIFY = _common.project_root() / "mocks/mgnify/results/2025-08-20_snapshot"

# Recipe parameters (manuscript)
N_REPLICATES = 10              # match existing non-env biome layout
SEQS_PER_REPLICATE = 75        # match lung's ~73, range 71-75 per file
MAX_POOL_SIZE = 500            # manuscript: "up to 500 sequences"
MUT_RATE_MIN = 0.002           # manuscript range
MUT_RATE_MAX = 0.02            # manuscript range
RNG_SEED = 20260509

# Cells built by this script: (biome dir, region, MGnify name)
BROKEN_CELLS = [
    ("biome_marine",  "V1-V9", "marine"),   # (biome dir, region, mgnify name)
    ("biome_ocean",   "V1-V9", "ocean"),
    ("biome_plants",  "V1-V9", "plants"),
    ("gtdb_marine",   "RRN",   "marine"),
    ("gtdb_ocean",    "RRN",   "ocean"),
    ("gtdb_plants",   "RRN",   "plants"),
]


def parse_taxonomy(taxon: str) -> dict[str, str]:
    """Parse 'd__X; p__Y; c__Z; o__A; f__B; g__C; s__D' into a dict."""
    out = {}
    for chunk in taxon.split(";"):
        chunk = chunk.strip()
        if "__" in chunk:
            rank, val = chunk.split("__", 1)
            out[rank] = val
    return out


def load_taxonomy(tax_path: Path) -> dict[str, dict[str, str]]:
    """Read taxonomy.tsv → {feature_id: {rank: value}}."""
    out = {}
    with open(tax_path) as f:
        next(f)  # header
        for line in f:
            line = line.rstrip("\n")
            if "\t" not in line:
                continue
            fid, taxon = line.split("\t", 1)
            out[fid] = parse_taxonomy(taxon)
    return out


def load_fasta(fa_path: Path) -> dict[str, str]:
    """Read FASTA → {header: sequence}, strip whitespace + tabs in headers."""
    out, cur_id, buf = {}, None, []
    with open(fa_path) as f:
        for line in f:
            line = line.rstrip("\n")
            if line.startswith(">"):
                if cur_id is not None:
                    out[cur_id] = "".join(buf)
                cur_id = line[1:].split("\t")[0].split()[0]
                buf = []
            else:
                buf.append(line)
        if cur_id is not None:
            out[cur_id] = "".join(buf)
    return out


def load_mgnify_genus_csv(biome_short: str) -> list[tuple[str, int]]:
    """Read mocks/mgnify/<biome>_genus_top_100.csv → [(genus, abundance), ...]."""
    csv_path = MGNIFY / f"{biome_short}_genus_top_100.csv"
    if not csv_path.exists():
        raise FileNotFoundError(f"MGnify genus CSV not found: {csv_path}")
    rows = []
    with open(csv_path) as f:
        rd = csv.DictReader(f)
        for r in rd:
            try:
                rows.append((r["taxon"], int(r["total_abundance"])))
            except (KeyError, ValueError):
                continue
    return rows


def filter_pool_by_genus(
    fasta: dict[str, str],
    taxonomy: dict[str, dict[str, str]],
    mgnify_genera: list[tuple[str, int]],
    max_pool: int,
    rng: random.Random,
) -> list[tuple[str, str, int]]:
    """For each MGnify genus, find gg2/GROND entries whose g__ rank matches
    (tolerant of GTDB-style underscore suffixes like `_A`, `_672454`).
    Sample weighted by MGnify abundance up to `max_pool` sequences total.
    Returns list of (feature_id, sequence, mgnify_abundance_for_its_genus).
    """
    # group taxonomy by base-genus (strip trailing _X / _NNNN GTDB suffixes)
    base_genus_re = re.compile(r"^([A-Za-z][A-Za-z0-9]*?)(?:_[A-Z]?[a-zA-Z0-9]*)*$")
    by_base_genus: dict[str, list[str]] = {}
    for fid, ranks in taxonomy.items():
        g = ranks.get("g", "")
        if not g:
            continue
        # extract base before first GTDB suffix
        m = re.match(r"^([A-Za-z][A-Za-z0-9]*)", g)
        if not m:
            continue
        base = m.group(1)
        by_base_genus.setdefault(base, []).append(fid)

    # for each MGnify genus, tally candidate fids with abundance weight
    weighted_pool: list[tuple[str, int]] = []  # (fid, abundance_weight)
    for mg_genus, abundance in mgnify_genera:
        # also strip 'Candidatus' prefix from MGnify names if it's run together
        candidates = by_base_genus.get(mg_genus, [])
        if not candidates and mg_genus.startswith("Candidatus") and len(mg_genus) > 10:
            tail = mg_genus[len("Candidatus"):]
            candidates = by_base_genus.get(tail, [])
        for fid in candidates:
            weighted_pool.append((fid, abundance))

    if not weighted_pool:
        raise RuntimeError("No gg2/GROND entries matched any MGnify genus")

    # weighted sample without replacement up to max_pool
    fids = [fid for fid, _ in weighted_pool]
    weights = [w for _, w in weighted_pool]
    target = min(max_pool, len(set(fids)))
    selected: set[str] = set()
    # sample with replacement from weighted distribution, take unique
    # (manuscript is "selected up to 500 sequences", weighted by env abundance)
    safety = max(target * 50, 5000)
    while len(selected) < target and safety > 0:
        fid = rng.choices(fids, weights=weights, k=1)[0]
        selected.add(fid)
        safety -= 1
    pool = []
    for fid in selected:
        seq = fasta.get(fid)
        if not seq:
            continue
        pool.append((fid, seq, 1))
    rng.shuffle(pool)
    return pool


def mutate_sequence(seq: str, rate: float, rng: random.Random) -> str:
    """Per-base substitution at `rate`. Skips ambiguous bases (matches the
    `process_mock.mutate_sequence` semantics in src/process_mock.py:543)."""
    if rate <= 0:
        return seq
    bases = "ACGT"
    n = len(seq)
    n_mut = round(rate * n)
    if n_mut <= 0:
        return seq
    positions = rng.sample(range(n), min(n_mut, n))
    s = list(seq)
    for pos in positions:
        original = s[pos]
        if original not in bases:
            continue
        alts = [b for b in bases if b != original]
        s[pos] = rng.choice(alts)
    return "".join(s)


def write_fasta(path: Path, records: list[tuple[str, str]]):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        for hid, seq in records:
            f.write(f">{hid}\n{seq}\n")


def md5_hash(seq: str) -> str:
    return hashlib.md5(seq.upper().encode()).hexdigest()


def regenerate_one(
    biome_dir: str,
    region: str,
    mgnify_short: str,
    *,
    dry_run: bool = False,
    force: bool = False,
):
    print(f"\n=== {biome_dir} × {region} (mgnify={mgnify_short}) ===")
    biome_path = MOCK / biome_dir / region

    # Pick reference DB
    if region == "V1-V9":
        ref_fa, ref_tax = GG2_FA, GG2_TAX
    elif region == "RRN":
        ref_fa, ref_tax = GROND_FA, GROND_TAX
    else:
        raise ValueError(f"Unsupported region for this fix: {region}")
    print(f"  ref fasta:    {ref_fa}")
    print(f"  ref taxonomy: {ref_tax}")

    print("  loading reference taxonomy...", flush=True)
    tax = load_taxonomy(ref_tax)
    print(f"    {len(tax):,} taxonomy rows")
    print("  loading reference fasta...", flush=True)
    fa = load_fasta(ref_fa)
    print(f"    {len(fa):,} sequences")

    print(f"  reading MGnify {mgnify_short} genus top-100...", flush=True)
    mg_genera = load_mgnify_genus_csv(mgnify_short)
    print(f"    {len(mg_genera)} genera, "
          f"abundance sum={sum(a for _, a in mg_genera):,}")

    # Stable across processes (the built-in hash() of a str is salted).
    rng = random.Random(RNG_SEED ^ zlib.crc32(f"{biome_dir}|{region}".encode()))

    print(f"  building candidate pool (target ≤ {MAX_POOL_SIZE} seqs)...", flush=True)
    pool = filter_pool_by_genus(fa, tax, mg_genera, MAX_POOL_SIZE, rng)
    print(f"    pool size: {len(pool)} sequences "
          f"(avg len: {sum(len(s) for _, s, _ in pool) / max(1, len(pool)):.0f} bp)")

    if dry_run:
        print("  [dry-run] skipping write")
        return

    # Generate 10 replicate env-seqs files
    all_replicate_records = []
    for i in range(N_REPLICATES):
        # subsample without replacement
        k = min(SEQS_PER_REPLICATE, len(pool))
        subsample = rng.sample(pool, k)
        rate = rng.uniform(MUT_RATE_MIN, MUT_RATE_MAX)
        mutated = []
        for fid, seq, _ in subsample:
            new_seq = mutate_sequence(seq, rate, rng)
            mutated.append((fid, new_seq))
            all_replicate_records.append((fid, new_seq))
        out_path = biome_path / f"env-seqs_{biome_dir}{i:02d}.fasta"
        write_fasta(out_path, mutated)
        print(f"  + replicate {i:02d}: rate={rate:.4f}, n={len(mutated)}, "
              f"avg_len={sum(len(s) for _, s in mutated) / max(1, len(mutated)):.0f} bp"
              f" → {out_path.name}")

    # Dereplicate union → rep_seqs with MD5-hash IDs (DADA2-style).
    # Track the source feature_id of the first sequence to hash to each MD5
    # so we can derive a trueish-taxonomy file from the reference taxonomy.
    seen = {}            # md5 -> seq
    md5_to_src_fid = {}  # md5 -> source feature_id (first hit wins)
    for src_fid, seq in all_replicate_records:
        h = md5_hash(seq)
        if h not in seen:
            seen[h] = seq
            md5_to_src_fid[h] = src_fid
    rep_records = list(seen.items())
    rep_path = biome_path / "source" / "single" / f"rep_seqs_{biome_dir}.fasta"
    write_fasta(rep_path, rep_records)
    print(f"  + rep_seqs: {len(rep_records)} unique ASVs "
          f"(avg_len={sum(len(s) for _, s in rep_records) / max(1, len(rep_records)):.0f} bp)"
          f" → {rep_path}")

    # Trueish taxonomy: map each new MD5 ID → taxonomy of its source ref entry.
    # Canonical 7-rank string `d__...; p__...; ...; s__...` matching the format
    # taxobench's evaluator expects. Reads source taxonomy strings raw from the
    # ref_tax file (avoids any rank-string reformatting).
    raw_tax: dict[str, str] = {}
    with open(ref_tax) as f:
        next(f)
        for line in f:
            line = line.rstrip("\n")
            if "\t" not in line:
                continue
            fid, tax_str = line.split("\t", 1)
            raw_tax[fid] = tax_str
    tax_path = biome_path / f"trueish_taxonomy_{biome_dir}.tsv"
    n_with_tax = 0
    with open(tax_path, "w") as f:
        f.write("id\ttaxonomy\n")
        for h in seen:
            src = md5_to_src_fid[h]
            t = raw_tax.get(src, "")
            if t:
                n_with_tax += 1
            f.write(f"{h}\t{t}\n")
    print(f"  + trueish_tax: {n_with_tax}/{len(seen)} mapped → {tax_path.name}")

    # Move broken legacy file aside
    legacy = biome_path / "single" / f"rep_seqs_{biome_dir}.fasta"
    if legacy.exists():
        suffix = f".broken_200bp_aside_{date.today().isoformat()}"
        target = legacy.with_suffix(legacy.suffix + suffix)
        if target.exists() and not force:
            print(f"  ! legacy already moved: {target.name}")
        else:
            shutil.move(str(legacy), str(target))
            print(f"  ✂ moved broken legacy: {legacy.name} → {target.name}")
    else:
        print(f"  - no legacy file to move at {legacy}")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--biome", help="biome dir, e.g. biome_marine or gtdb_marine")
    ap.add_argument("--region", help="V1-V9 or RRN")
    ap.add_argument("--mgnify", help="MGnify short name (default: derived from --biome)")
    ap.add_argument("--all", action="store_true", help="build all six cells")
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    if args.all:
        cells = BROKEN_CELLS
    else:
        if not (args.biome and args.region):
            ap.error("specify --biome AND --region (or --all)")
        mg = args.mgnify or args.biome.split("_", 1)[1]  # strip "biome_"/"gtdb_" prefix
        cells = [(args.biome, args.region, mg)]

    for biome_dir, region, mgnify_short in cells:
        regenerate_one(biome_dir, region, mgnify_short,
                       dry_run=args.dry_run, force=args.force)
    print("\ndone.")


if __name__ == "__main__":
    main()
